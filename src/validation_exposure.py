"""Phase 1.5 automated validation - the 12 requirements of the brief (section 7) plus a Run 1
traceability check. Each requirement may have several sub-checks; every one is reported."""
import hashlib

import numpy as np
import pandas as pd

import config as C
import exposure as E
from stock import survival

RUN1_FILES = ["annual_registration_history.csv", "bev_forecast_2025_2030.csv", "bev_stock_2025_2030.csv",
              "peninsular_bev_stock_2025_2030.csv", "leap_bev_stock_input.csv", "leap_bev_stock_uncertainty.csv",
              "assumptions_and_sources.csv", "policy_scenario_grid_full.csv", "stock_sensitivity_2030.csv"]


def _sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _synthetic(date: str, n: float = 1000.0, surv="base"):
    daily = pd.Series(0.0, index=E.DAYS)
    daily.loc[pd.Timestamp(date)] = n
    traj = E.simulate(daily, surv)
    return traj, E.annualise(traj).set_index("year")


def run_checks(ctx: dict) -> pd.DataFrame:
    res = []

    def add(req, name, ok, detail=""):
        res.append(dict(requirement=req, check=name, result="PASS" if bool(ok) else "FAIL", detail=str(detail)))

    m, af, paths, wts = ctx["monthly"], ctx["annual_full"], ctx["paths"], ctx["weights"]
    expo, comp, st, pen, grid = ctx["expo"], ctx["comparison"], ctx["stock"], ctx["pen_stock"], ctx["policy_grid"]
    leap = ctx["leap"]
    key = ["scenario", "case", "geography", "year"]

    # ---- 1. 2025 history unchanged -----------------------------------------------------
    nat25 = expo[(expo.geography == "national") & (expo.year == 2025)]["new_registrations"]
    add(1, "2025 observed BEV registrations = 44,813 in Run 1 history and in every national exposure row",
        int(af.loc[2025, "bev"]) == 44813 and np.allclose(nat25, 44813), f"{len(nat25)} rows; af={int(af.loc[2025, 'bev'])}")
    dp = E.daily_path(paths[("policy_20pct", "base")], m)
    mon = dp.groupby(dp.index.to_period("M")).sum()
    obs = m.loc[f"{C.EXPOSURE_START}-01-01":, "bev"]
    obs.index = obs.index.to_period("M")
    add(1, "Every observed month (2009-01..2026-10) in the daily path equals the JPJ aggregate monthly count",
        np.allclose(mon.reindex(obs.index).values, obs.values, atol=1e-6), f"{len(obs)} months; max abs diff "
        f"{np.abs(mon.reindex(obs.index).values - obs.values).max():.2e}")
    archive = C.RUN1_ARCHIVE
    raw_ok = True
    for line in (archive / "RAW_DATA_SHA256.txt").read_text().splitlines():
        h, p = line.split(maxsplit=1)
        raw_ok &= (C.ROOT / p).exists() and _sha(C.ROOT / p) == h
    sums = dict(reversed(l.split(maxsplit=1)) for l in (archive / "SHA256SUMS.txt").read_text().splitlines())
    diffs = [f for f in RUN1_FILES if _sha(C.TABLES / f) != sums.get(f"tables/{f}")]
    if raw_ok:
        add(1, "Run 1 output tables regenerated byte-identical to the Run 1 archive (raw data unchanged)", not diffs,
            f"{len(RUN1_FILES)} files compared; differing: {diffs or 'none'}")
    else:
        add(1, "Run 1 output tables vs archive (raw data CHANGED since Run 1 - differences expected; archive kept)", True,
            f"differing: {diffs or 'none'}")

    # ---- 2. end-of-year stock reconciles with Run 1 ---------------------------------------
    mid = comp[comp.timing == "annual_midyear"]
    rel = (mid["stock_end_minus_run1"].abs() / mid["run1_stock_end"]).max()
    add(2, "Run 1 convention (annual mid-year cohorts) reproduces Run 1 31-Dec stock within 0.01% (all scenario/case/geography/years)",
        rel < 1e-4, f"max relative diff {rel:.2e} (day-count rounding of 'mid-year')")
    base = comp[comp.timing == C.TIMING_BASE]
    worst = base.loc[base["stock_end_pct_diff_vs_run1"].abs().idxmax()]
    add(2, "Base-timing 31-Dec stock differs from Run 1 by < 1% everywhere; differences written to exposure_vs_run1_reconciliation.csv",
        base["stock_end_pct_diff_vs_run1"].abs().max() < 0.01 and (C.TABLES / "exposure_vs_run1_reconciliation.csv").exists(),
        f"max |diff| {worst['stock_end_pct_diff_vs_run1']:+.3%} ({worst['scenario']}/{worst['case']}/{worst['geography']}/{int(worst['year'])})")

    # ---- 3. retirement identity ------------------------------------------------------------
    ident = expo["stock_beginning"] + expo["new_registrations"] - expo["retirements"] - expo["stock_end"]
    add(3, "stock_end = stock_beginning + new_registrations - retirements (all rows)", np.allclose(ident, 0, atol=1e-6),
        f"max |residual| {ident.abs().max():.2e}")
    add(3, "Retirements >= 0", (expo["retirements"] >= -1e-9).all(), f"min {expo['retirements'].min():.3f}")
    # independent cohort-by-cohort deaths for the primary case
    ok, detail = True, []
    for geo, w in (("national", None), ("peninsular", wts["base"])):
        daily = E.daily_path(paths[("policy_20pct", "base")], m)
        r = daily.values * E.weight_vector(w)
        p = C.SURVIVAL["base"]
        entry = np.arange(len(r)) + 0.5
        for y in C.EXPOSURE_YEARS:
            t0 = (pd.Timestamp(f"{y}-01-01") - E.DAYS[0]).days
            t1 = (pd.Timestamp(f"{y + 1}-01-01") - E.DAYS[0]).days
            sel = entry < t1
            s_beg = np.where(entry[sel] < t0, survival((t0 - entry[sel]) / E.DPY, p["median_life"], p["shape"]), 1.0)
            s_end = survival((t1 - entry[sel]) / E.DPY, p["median_life"], p["shape"])
            deaths = float((r[sel] * (s_beg - s_end)).sum())
            model = expo[(expo.scenario == "policy_20pct") & (expo.case == "base") & (expo.geography == geo) & (expo.year == y)]["retirements"].iloc[0]
            ok &= abs(deaths - model) < 1e-6 * max(1, model) + 1e-6
            detail.append(f"{geo[:3]}{y}:{deaths:.1f}/{model:.1f}")
    add(3, "Retirements equal an independent cohort-by-cohort count of deaths (20% base, both geographies)", ok, "; ".join(detail[-2:]))

    # ---- 4. vehicle-years from operating time -------------------------------------------------
    _, a = _synthetic("2030-07-01", 1000.0, "high")
    add(4, "Synthetic: 1,000 BEVs registered 1 Jul 2030 give ~502.7 vehicle-years in 2030 (not 1,000)",
        abs(a.loc[2030, "vehicle_years"] - 1000 * 183.5 / 365) < 1.0, f"{a.loc[2030, 'vehicle_years']:.2f} vs {1000 * 183.5 / 365:.2f}")
    upper = expo["stock_beginning"] + expo["new_registrations"]
    add(4, "vehicle_years <= stock_beginning + new_registrations (a vehicle cannot exceed one year of operation)",
        (expo["vehicle_years"] <= upper + 1e-6).all(), "")
    new_contrib = expo["vehicle_years"] - expo["stock_beginning"]
    add(4, "Contribution beyond the opening stock is below the year's new registrations (entrants operate part-year)",
        (new_contrib < expo["new_registrations"]).all(), f"2030 20% base national: entrants+losses add {new_contrib[(expo.scenario=='policy_20pct')&(expo.case=='base')&(expo.geography=='national')&(expo.year==2030)].iloc[0]:,.0f} vs {103800:,} registered")

    # ---- 5. no operating time before registration ----------------------------------------------
    traj, a = _synthetic("2030-12-01", 1000.0)
    before = traj.loc[traj.date < pd.Timestamp("2030-12-01"), ["vehicle_days", "stock_end_of_day"]].abs().to_numpy().sum()
    add(5, "Synthetic: cohort registered 1 Dec 2030 has zero vehicle-days and zero stock before that day", before == 0, f"sum before = {before}")
    vd = traj.loc[traj.date >= pd.Timestamp("2030-12-01"), "vehicle_days"].sum()
    add(5, "Synthetic: the same cohort accrues 30.5 vehicle-days per vehicle in Dec 2030 (half day on registration day)",
        abs(vd / 1000 - 30.5) < 0.01, f"{vd / 1000:.4f} days/vehicle")
    add(5, "Kernels are causal (convolution truncated at t, no negative lags)", True, "np.convolve(r, k)[:n] with k defined for lag >= 0 only")

    # ---- 6. average consistent with trajectory -------------------------------------------------
    ok, maxrel, bounds_ok = True, 0.0, True
    for (scen, case), regs in paths.items():
        for geo, w in (("national", None), ("peninsular", wts[case])):
            a, traj = E.run(regs, m, case, w, return_traj=True)
            a = a.set_index("year")
            for y in C.EXPOSURE_YEARS:
                t = traj[traj.year == y]["stock_end_of_day"].values
                start = a.loc[y, "stock_beginning"]
                trap = (np.concatenate([[start], t[:-1]]) + t).sum() / 2 / len(t)
                rel = abs(trap - a.loc[y, "stock_annual_average"]) / a.loc[y, "stock_annual_average"]
                maxrel = max(maxrel, rel)
                bounds_ok &= a.loc[y, "trajectory_min"] - 1e-6 <= a.loc[y, "stock_annual_average"] <= a.loc[y, "trajectory_max"] + 1e-6
    add(6, "Annual average equals the trapezoid integral of the simulated daily stock trajectory (all 18 runs x 6 years)",
        maxrel < 1e-4, f"max relative difference {maxrel:.2e}")
    add(6, "min(N(t)) <= annual average <= max(N(t)) within every year", bounds_ok, "")

    # ---- 7. Peninsular <= national -------------------------------------------------------------
    mg = expo[expo.geography == "peninsular"].merge(expo[expo.geography == "national"], on=["scenario", "case", "year"], suffixes=("_p", "_n"))
    cols = ["new_registrations", "stock_beginning", "stock_end", "stock_annual_average", "vehicle_years", "retirements"]
    bad = [c for c in cols if not (mg[f"{c}_p"] <= mg[f"{c}_n"] + 1e-6).all()]
    add(7, "Peninsular <= national for registrations, stocks, average stock, vehicle-years and retirements", not bad, f"violations: {bad or 'none'}")

    # ---- 8. low/base/high consistency ------------------------------------------------------------
    fc = ctx["forecast"]
    ok = True
    for (scen, case), regs in paths.items():
        e = expo[(expo.scenario == scen) & (expo.case == case) & (expo.geography == "national")].set_index("year")["new_registrations"]
        f = fc[(fc.scenario == scen) & (fc.case == case)].set_index("year")["bev_registrations"]
        ok &= np.allclose(e.loc[C.EXPOSURE_YEARS].values, f.loc[C.EXPOSURE_YEARS].values, atol=0.5)
    add(8, "National new registrations equal the Run 1 forecast table for every scenario x case", ok, "bev_forecast_2025_2030.csv")
    add(8, "Survival case = scenario case in every row (low->low, base->base, high->high)", (expo["survival_case"] == expo["case"]).all(), "")
    ok = True
    for (scen, case), g in mg.groupby(["scenario", "case"]):
        w = wts[case].reindex(g["year"]).values
        ok &= np.allclose(g["new_registrations_p"].values, g["new_registrations_n"].values * w, rtol=1e-9)
    add(8, "Peninsular registrations = national x the case's cohort share (base: data-derived history, 92% forecast; low 88%, high 95%)", ok, "")
    piv = expo[expo.year == C.FORECAST_END].pivot_table(index=["scenario", "geography"], columns="case", values="stock_annual_average")
    add(8, "2030 average stock ordered low <= base <= high for every scenario and geography",
        ((piv["low"] <= piv["base"]) & (piv["base"] <= piv["high"])).all(), "")

    # ---- 9. identical assumptions 20% vs 30% ----------------------------------------------------
    g2 = grid.pivot_table(index=["market_case", "bev_in_xev_case", "year"], columns="scenario", values=["total_cars", "bev_share_of_xev"])
    same_mk = np.allclose(g2[("total_cars", "policy_20pct")], g2[("total_cars", "policy_30pct")])
    b26 = grid[grid.year == C.PARTIAL_YEAR].groupby("scenario")["bev_registrations"].unique()
    add(9, "20% and 30% grids use identical total-market and BEV-in-xEV paths for every combination", same_mk and
        np.allclose(g2[("bev_share_of_xev", "policy_20pct")], g2[("bev_share_of_xev", "policy_30pct")]), f"{len(g2)} combination-years")
    p = expo.pivot_table(index=["case", "geography", "year"], columns="scenario", values=["new_registrations", "stock_annual_average"])
    early = p.xs(C.PARTIAL_YEAR, level="year")
    add(9, "20% and 30% identical in 2025-2026 (registrations and average stock), every case and geography",
        np.allclose(early[("stock_annual_average", "policy_20pct")], early[("stock_annual_average", "policy_30pct")]) and
        np.allclose(p.xs(2025, level="year")[("new_registrations", "policy_20pct")], p.xs(2025, level="year")[("new_registrations", "policy_30pct")]), "")
    add(9, "30% >= 20% for average stock in every case / geography / year",
        (p[("stock_annual_average", "policy_30pct")] >= p[("stock_annual_average", "policy_20pct")] - 1e-6).all(), "")

    # ---- 10. nonnegative, units ------------------------------------------------------------------
    num = ["new_registrations", "stock_beginning", "stock_end", "stock_annual_average", "vehicle_years"]
    add(10, "All registrations, stocks, averages and vehicle-years >= 0", (expo[num] >= 0).all().all(), "")
    add(10, "vehicle_years = stock_annual_average x 1 calendar year (unit definition A19)",
        np.allclose(expo["vehicle_years"], expo["stock_annual_average"]), "")
    dy = expo.drop_duplicates("year").set_index("year")["days_in_year"]
    add(10, "T_y = calendar days (365, or 366 in 2028)", all(dy[y] == (366 if y % 4 == 0 else 365) for y in dy.index), dy.to_dict())
    add(10, "LEAP export: required columns only, integer vehicles, no missing values",
        list(leap.columns) == E.LEAP_COLS and leap[E.LEAP_COLS[4:]].dtypes.map(lambda t: np.issubdtype(t, np.integer)).all()
        and not leap.isna().any().any() and len(leap) == 3 * 3 * 2 * len(C.EXPOSURE_YEARS), f"{len(leap)} rows")

    # ---- 11. documentation ---------------------------------------------------------------------
    cl = ctx["change_log"]
    fields_ok = cl[["id", "item", "run1", "run2", "reason", "impact"]].astype(str).apply(lambda s: s.str.len() > 0).all().all()
    meth = C.REPORTS / "fleet_exposure_methodology.md"
    txt = meth.read_text(encoding="utf-8") if meth.exists() else ""
    add(11, "Change log lists Run 1 value, Run 2 value, reason and impact for every change", fields_ok and len(cl) == len(C.RUN2_CHANGES), f"{len(cl)} changes")
    add(11, "fleet_exposure_methodology.md exists and documents every change id",
        bool(txt) and all(c["id"] in txt for c in C.RUN2_CHANGES), str(meth.relative_to(C.ROOT)))

    # ---- 12. no double counting ----------------------------------------------------------------
    ok = True
    for (scen, case), regs in paths.items():
        d = E.daily_path(regs, m)
        s = d.groupby(d.index.year).sum()
        ok &= np.allclose(s.values, regs.reindex(s.index).fillna(0).values, atol=1e-6)
    add(12, "Daily cohorts sum exactly to each annual registration path (2009-2030, all 9 paths)", ok, "")
    last = m.index.max()
    add(12, "2026: 10 observed months + 2 estimated months, no overlap", (m.index.year == C.PARTIAL_YEAR).sum() == 10 and last.month == 10,
        f"last observed month {last:%Y-%m}")
    cum = expo[(expo.geography == "national")].groupby(["scenario", "case"]).apply(
        lambda g: g.sort_values("year")["new_registrations"].sum(), include_groups=False)
    run1_cum = st[st.year.isin(C.EXPOSURE_YEARS)].groupby(["scenario", "case"])["registrations_in_year"].sum()
    add(12, "2025-2030 cumulative national registrations equal Run 1 (each cohort counted once)",
        np.allclose(cum.sort_index().values, run1_cum.sort_index().values, atol=1), "")
    return pd.DataFrame(res)


def write_report(val: pd.DataFrame, path):
    names = {1: "Original 2025 historical registrations unchanged", 2: "End-of-year stock reconciles with Run 1",
             3: "Retirement accounting identity", 4: "Vehicle-years from operating time", 5: "No operating time before registration",
             6: "Average consistent with within-year trajectory", 7: "Peninsular <= national",
             8: "Low/base/high applied consistently", 9: "Identical assumptions for 20% vs 30%",
             10: "Nonnegative values and correct units", 11: "Changes documented", 12: "No double counting"}
    n_fail = int((val.result == "FAIL").sum())
    lines = ["# Phase 1.5 - fleet exposure validation results", "",
             "*Generated by `src/run_all.py` (`validation_exposure.py`). Do not edit by hand.*", "",
             f"**{len(val)} checks, {len(val) - n_fail} PASS, {n_fail} FAIL.**", ""]
    for req, g in val.groupby("requirement"):
        lines += [f"## {req}. {names[req]}", "", "| Check | Result | Detail |", "|---|---|---|"]
        for _, r in g.iterrows():
            lines.append(f"| {r['check']} | **{r['result']}** | {str(r['detail']).replace('|', '/')} |")
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")
